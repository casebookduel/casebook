// Icons drawn as dot grids, in the same medium as the agents. Each icon is a 9x9 bitmap.
const ICONS: Record<string, string[]> = {
  chain: ["000000000", "011101110", "010101010", "011111110", "000101000", "011111110", "010101010", "011101110", "000000000"],
  key: ["000000000", "001110000", "010001000", "010001000", "001110000", "000100000", "000111000", "000100000", "000111000"],
  agents: ["000000000", "011000110", "111101111", "011000110", "000000000", "011000110", "111101111", "111101111", "000000000"],
  check: ["000000000", "000000001", "000000011", "000000110", "100001100", "110011000", "011110000", "001100000", "000000000"],
  trail: ["000000000", "000000011", "000000110", "010001100", "111011000", "101110000", "100100000", "000000000", "111111111"],
  flame: ["000010000", "000110000", "001110100", "001111100", "011111110", "011101110", "011000110", "001101100", "000111000"],
  podium: ["000111000", "000101000", "000111000", "111111000", "101101111", "111101101", "100101111", "100101001", "111111111"],
  note: ["011111100", "010000110", "010000010", "011111010", "010000010", "011110010", "010000010", "010000010", "011111110"],
};
export default function Pixel({ name, size = 72 }: { name: keyof typeof ICONS | string; size?: number }) {
  const rows = ICONS[name] ?? ICONS.chain, s = size / 9;
  return (
    <svg width={size} height={size} viewBox={`0 0 ${size} ${size}`} aria-hidden="true" className="pixel">
      {rows.flatMap((r, y) => [...r].map((b, x) => (
        <circle key={`${x}-${y}`} cx={x * s + s / 2} cy={y * s + s / 2} r={b === "1" ? s * 0.36 : s * 0.12} className={b === "1" ? "on" : "off"} />
      )))}
    </svg>
  );
}
